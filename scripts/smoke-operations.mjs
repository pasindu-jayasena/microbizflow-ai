import assert from 'node:assert/strict';

const base='http://127.0.0.1:8788';
const password=process.env.LOCAL_OWNER_PASSWORD?.trim();
const automationToken=process.env.LOCAL_AUTOMATION_TICK_TOKEN?.trim();
if(!password||!automationToken) throw new Error('Set disposable local owner password and automation token.');
const post=(path,body,headers={})=>fetch(`${base}${path}`,{method:'POST',headers:{'Content-Type':'application/json',...headers},body:JSON.stringify(body)});
assert.equal((await post('/api/owner/assistant/query',{question:'How many pending appointments?'})).status,401);
assert.equal((await post('/api/automation/assistant',{question:'How many pending appointments?'})).status,401);
const signed=await post('/api/owner/login',{username:'owner',password});
assert.equal(signed.status,200);
const cookie=signed.headers.get('set-cookie')?.split(';')[0];
assert.ok(cookie);
const owner=(path,body)=>post(path,body,{Cookie:cookie});
const report=await owner('/api/owner/assistant/query',{question:'How many pending appointments?'});
assert.equal(report.status,200);
const count=await report.json();
assert.equal(count.intent,'pending_count');
assert.match(count.answer,/awaiting owner approval/);
const catalogue=await fetch(`${base}/api/business`).then(r=>r.json());
const service=catalogue.services.find(item=>item.id==='svc_cut');
assert.ok(service);
const oldPrice=service.priceMinor??service.price_minor;
assert.ok(Number.isInteger(oldPrice));
const newPrice=oldPrice+10000<=10000000?oldPrice+10000:oldPrice-10000;
const question=`Set ${service.name} price to LKR ${newPrice/100}`;
const proposalResponse=await owner('/api/owner/assistant/query',{question});
assert.equal(proposalResponse.status,200);
const proposal=await proposalResponse.json();
assert.equal(proposal.intent,'propose_price');
assert.ok(proposal.proposalId);
const unchanged=await fetch(`${base}/api/business`).then(r=>r.json());
assert.equal(unchanged.services.find(item=>item.id===service.id)?.priceMinor??unchanged.services.find(item=>item.id===service.id)?.price_minor,oldPrice);
assert.equal((await post(`/api/owner/assistant/proposals/${proposal.proposalId}/approve`,{}, {Authorization:`Bearer ${automationToken}`})).status,401);
const approved=await owner(`/api/owner/assistant/proposals/${proposal.proposalId}/approve`,{});
assert.equal(approved.status,200);
assert.equal((await approved.json()).state,'approved');
assert.equal((await owner(`/api/owner/assistant/proposals/${proposal.proposalId}/approve`,{})).status,409);
const changed=await fetch(`${base}/api/business`).then(r=>r.json());
assert.equal(changed.services.find(item=>item.id===service.id)?.priceMinor??changed.services.find(item=>item.id===service.id)?.price_minor,newPrice);
const stalePrice=newPrice+20000<=10000000?newPrice+10000:newPrice-10000;
const staleResult=await owner('/api/owner/assistant/query',{question:`Set ${service.name} price to LKR ${stalePrice/100}`});
assert.equal(staleResult.status,200);
const stale=await staleResult.json();
assert.ok(stale.proposalId);
const manualPrice=stalePrice+10000<=10000000?stalePrice+10000:stalePrice-10000;
const editPrice=priceMinor=>fetch(`${base}/api/owner/services/${service.id}`,{method:'PATCH',headers:{Cookie:cookie,'Content-Type':'application/json'},body:JSON.stringify({name:service.name,description:service.description,durationMin:service.duration_min,priceMinor,active:true})});
assert.equal((await editPrice(manualPrice)).status,200);
assert.equal((await owner(`/api/owner/assistant/proposals/${stale.proposalId}/approve`,{})).status,409);
assert.equal((await editPrice(newPrice)).status,200);
assert.equal((await owner(`/api/owner/assistant/proposals/${stale.proposalId}/reject`,{})).status,200);
const serviceAnswer=await post('/api/automation/assistant',{question:'List service prices'},{Authorization:`Bearer ${automationToken}`});
assert.equal(serviceAnswer.status,200);
assert.equal((await serviceAnswer.json()).intent,'service_catalogue');
const historyResponse=await fetch(`${base}/api/owner/assistant/history`,{headers:{Cookie:cookie}});
assert.equal(historyResponse.status,200);
const history=await historyResponse.json();
assert.ok(history.runs.some(run=>run.intent==='pending_count'));
assert.ok(history.proposals.some(item=>item.id===proposal.proposalId&&item.state==='approved'));
assert.ok(!JSON.stringify(history).includes(question),'History must not store the original question');
console.log('Local operations assistant passed: private read queries, scoped automation, approval-only price update, stale and duplicate guards, audit history.');
