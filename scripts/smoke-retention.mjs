import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { Temporal } from '@js-temporal/polyfill';

const base = 'http://127.0.0.1:8788';
const password = process.env.LOCAL_OWNER_PASSWORD;
if (!password) throw new Error('Set LOCAL_OWNER_PASSWORD to the local owner password for this test.');
const groups = crypto.randomUUID().replaceAll('-', '').match(/.{4}/g);
const headers = { 'Content-Type': 'application/json', 'CF-Connecting-IP': `2001:db8:${groups.slice(0, 6).join(':')}` };
const catalogue = await fetch(`${base}/api/business`).then(response => response.json());
const today = Temporal.Now.zonedDateTimeISO(catalogue.business.timezone).toPlainDate();
let date = '';
let time = '';
for (let offset = 2; offset <= 9; offset++) {
  date = today.add({ days: offset }).toString();
  const available = await fetch(`${base}/api/availability?serviceId=svc_cut&date=${date}`).then(response => response.json());
  if (available.slots?.length) { time = available.slots[0]; break; }
}
assert.ok(time, 'A future slot is required');
const contact = `retention-${crypto.randomUUID()}@example.invalid`;
const key = crypto.randomUUID();
const booked = await fetch(`${base}/api/bookings`, { method: 'POST', headers, body: JSON.stringify({
  serviceId: 'svc_cut', date, time, customerName: 'Fictional Retention Test', customerContact: contact,
  note: 'Synthetic retention note', idempotencyKey: key,
}) });
assert.equal(booked.status, 201);
const { reference } = await booked.json();
const login = await fetch(`${base}/api/owner/login`, { method: 'POST', headers, body: JSON.stringify({ username: 'owner', password }) });
assert.equal(login.status, 200);
const cookie = login.headers.get('set-cookie')?.split(';')[0];
assert.ok(cookie?.startsWith('mbf_session='));
const owner = (path, init = {}) => fetch(`${base}${path}`, { ...init, headers: { Cookie: cookie, ...init.headers } });
assert.equal((await fetch(`${base}/api/owner/retention/run`, { method: 'POST' })).status, 401);
const first = await owner('/api/owner/retention/run', { method: 'POST' });
assert.equal(first.status, 200);
assert.equal((await owner(`/api/owner/customers/${encodeURIComponent(contact)}`)).status, 200, 'Active booking must remain');
const cancelled = await fetch(`${base}/api/bookings/cancel`, { method: 'POST', headers, body: JSON.stringify({ reference, cancellationCode: key }) });
assert.equal(cancelled.status, 200);
const second = await owner('/api/owner/retention/run', { method: 'POST' });
assert.equal(second.status, 200);
assert.equal((await owner(`/api/owner/customers/${encodeURIComponent(contact)}`)).status, 200, 'Recent cancelled booking must remain');
const analyzed = await fetch(`${base}/api/enquiries/analyze`, { method: 'POST', headers,
  body: JSON.stringify({ text: 'I need a haircut tomorrow', consentExternalAI: false }) });
assert.equal(analyzed.status, 200);
const { analysisId } = await analyzed.json();
assert.match(analysisId, /^[0-9a-f-]{36}$/);

// Move only this fictional, terminal appointment into the past in local D1.
// The reference is generated by the API and constrained to uppercase hex.
assert.match(reference, /^MBF-[A-F0-9]{8}$/);
execFileSync('node', ['scripts/wrangler.mjs', 'd1', 'execute', 'microbizflow-local', '--config', 'wrangler.worker.toml', '--local',
  '--command', `UPDATE appointments SET start_at='2024-01-01T00:00:00.000Z',end_at='2024-01-01T00:30:00.000Z' WHERE reference='${reference}' AND status='cancelled'`], { stdio: 'pipe' });
execFileSync('node', ['scripts/wrangler.mjs', 'd1', 'execute', 'microbizflow-local', '--config', 'wrangler.worker.toml', '--local',
  '--command', `UPDATE enquiry_analyses SET created_at='2024-01-01 00:00:00' WHERE id='${analysisId}' AND appointment_id IS NULL`], { stdio: 'pipe' });
const third = await owner('/api/owner/retention/run', { method: 'POST' });
assert.equal(third.status, 200, await third.clone().text());
const result = await third.json();
assert.ok(result.deletedCustomers >= 1);
assert.ok(result.anonymizedBookings >= 1);
assert.ok(result.deletedEnquiries >= 1);
assert.equal((await owner(`/api/owner/customers/${encodeURIComponent(contact)}`)).status, 404);
assert.ok(!(await owner('/api/owner/enquiries').then(response => response.json())).enquiries.some(item => item.id === analysisId));
const appointments = await owner(`/api/owner/appointments?q=${encodeURIComponent(reference)}`).then(response => response.json());
assert.equal(appointments.appointments.find(item => item.reference === reference)?.customer_name, 'Deleted customer');
console.log('Local retention test passed: private access, active and recent guards, and 365-day customer and enquiry purge.');
